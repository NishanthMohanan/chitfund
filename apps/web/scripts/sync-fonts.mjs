// Copies the IBM Plex subsets the app uses from @ibm/plex into public/fonts and
// regenerates src/styles/fonts.css. Run after upgrading @ibm/plex:
//   pnpm --filter @chitfund/web fonts:sync
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const plexRoot = dirname(require.resolve('@ibm/plex/package.json'));
const webRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(webRoot, 'public', 'fonts');

// Latin1 covers ASCII and common punctuation; Latin2 carries the rupee sign (U+20B9).
const SUBSETS = ['Latin1', 'Latin2'];
const FACES = [
  {
    family: 'IBM Plex Sans',
    dir: 'IBM-Plex-Sans',
    file: 'IBMPlexSans',
    style: 'Regular',
    weight: 400,
  },
  {
    family: 'IBM Plex Sans',
    dir: 'IBM-Plex-Sans',
    file: 'IBMPlexSans',
    style: 'Medium',
    weight: 500,
  },
  {
    family: 'IBM Plex Sans',
    dir: 'IBM-Plex-Sans',
    file: 'IBMPlexSans',
    style: 'SemiBold',
    weight: 600,
  },
  {
    family: 'IBM Plex Mono',
    dir: 'IBM-Plex-Mono',
    file: 'IBMPlexMono',
    style: 'Medium',
    weight: 500,
  },
];

async function unicodeRanges(face) {
  const css = await readFile(
    join(plexRoot, face.dir, 'fonts', 'split', 'woff2', `${face.file}-${face.style}.css`),
    'utf8',
  );
  const ranges = new Map();
  for (const block of css.split('@font-face').slice(1)) {
    const subset = /-(\w+)\.woff2/.exec(block)?.[1];
    const range = /unicode-range:\s*([^;}\n]+)/.exec(block)?.[1];
    if (subset && range) {
      ranges.set(subset, range.trim());
    }
  }
  return ranges;
}

await mkdir(outDir, { recursive: true });

const rules = [];
for (const face of FACES) {
  const ranges = await unicodeRanges(face);
  for (const subset of SUBSETS) {
    const source = `${face.file}-${face.style}-${subset}.woff2`;
    await copyFile(
      join(plexRoot, face.dir, 'fonts', 'split', 'woff2', source),
      join(outDir, source),
    );
    rules.push(
      [
        '@font-face {',
        `  font-family: '${face.family}';`,
        '  font-style: normal;',
        `  font-weight: ${face.weight};`,
        '  font-display: swap;',
        `  src: url('/fonts/${source}') format('woff2');`,
        `  unicode-range: ${ranges.get(subset)};`,
        '}',
      ].join('\n'),
    );
  }
}

const header = '/* Generated by scripts/sync-fonts.mjs from @ibm/plex. Do not edit by hand. */\n\n';
await writeFile(join(webRoot, 'src', 'styles', 'fonts.css'), `${header}${rules.join('\n\n')}\n`);
process.stdout.write(`Synced ${rules.length} font files to public/fonts\n`);
